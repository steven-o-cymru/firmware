def make_job(ff_print, tmp_path, origin="SDCARD_PRINT_FILE", on_file=None):
    calls = []
    job = ff_print.FFPrint.__new__(ff_print.FFPrint)
    job.printer = SimpleNamespace(lookup_object=lambda name, default=None:
                                  SimpleNamespace(sdcard_dirname=str(tmp_path)))
    job.gcode = SimpleNamespace(run_script_from_command=lambda script:
                                calls.append(("before", script)))
    job.before_macro = "FF_BEFORE_PRINT_START"
    job.previous_handlers = {origin: on_file or (lambda _gcmd:
                             calls.append(("file", origin)))}
    job.active = False
    return job, calls


def file_command(path):
    return SimpleNamespace(get=lambda key, default="": path.name,
                           get_raw_command_parameters=lambda: path.name)


@pytest.mark.parametrize("origin", ["SDCARD_PRINT_FILE", "M23"])
def test_ff_print_forwards_exact_tools_before_loading_file(ff_print, tmp_path,
                                                            origin):
    path = gcode_file(tmp_path, "4,1", "T0\nT3\n")
    job, calls = make_job(ff_print, tmp_path, origin)

    job._cmd_start(origin, file_command(path))

    assert calls == [
        ("before", "FF_BEFORE_PRINT_START ORIGIN=%s TOOL=0 TOOLS=0,3"
         % origin),
        ("file", origin),
    ]
    assert job.get_status(0)["tools"] == [0, 3]


def test_ff_print_omits_tools_when_file_has_no_header(
        ff_print, tmp_path):
    path = gcode_file(tmp_path, body="M140 S60\n", header=False)
    calls = []
    job = ff_print.FFPrint.__new__(ff_print.FFPrint)
    job.printer = SimpleNamespace(lookup_object=lambda name, default=None:
                                  SimpleNamespace(sdcard_dirname=str(tmp_path)))
    job.gcode = SimpleNamespace(run_script_from_command=calls.append)
    job.before_macro = "FF_BEFORE_PRINT_START"
    job.previous_handlers = {"SDCARD_PRINT_FILE": lambda _gcmd: None}
    gcmd = SimpleNamespace(get=lambda key, default="": path.name)

    job._cmd_start("SDCARD_PRINT_FILE", gcmd)

    assert calls == ["FF_BEFORE_PRINT_START ORIGIN=SDCARD_PRINT_FILE BED=60"]
    assert job.get_status(0)["tools"] == []


@pytest.fixture(scope="module")
def macro_templates():
    cp = configparser.RawConfigParser(
        strict=False, inline_comment_prefixes=(";", "#"))
    cp.read(MACROS)
    env = jinja2.Environment("{%", "%}", "{", "}")
    return {name: env.from_string(cp.get("gcode_macro " + name, "gcode"))
            for name in ("FF_BEFORE_PRINT_START", "START_PRINT",
                         "_FF_NOZZLE_CLEAN")}


def render(template, params, printer, rawparams=""):
    return template.render(params=params, printer=printer,
                           rawparams=rawparams,
                           action_respond_info=lambda _message: "")


def commands(output, prefix):
    return [line.strip() for line in output.splitlines()
            if line.strip().startswith(prefix)]


def test_automatic_preflight_and_clean_use_the_file_participants(macro_templates):
    printer = {"gcode_macro FF_BEFORE_PRINT_START":
               {"prepare": 1, "prepare_on_m23": 0}}
    params = {"ORIGIN": "SDCARD_PRINT_FILE", "TOOL": "0", "TOOLS": "0,3"}
    raw = "ORIGIN=SDCARD_PRINT_FILE TOOL=0 TOOLS=0,3"
    before = render(macro_templates["FF_BEFORE_PRINT_START"], params,
                    printer, raw)
    assert commands(before, "_FF_PREFLIGHT") == [
        "_FF_PREFLIGHT TOOL=0 TOOLS=0,3"]
    assert commands(before, "START_PRINT") == ["START_PRINT " + raw]

    start = render(macro_templates["START_PRINT"], params, printer)
    assert commands(start, "_FF_PREFLIGHT") == [
        "_FF_PREFLIGHT TOOL=0 TOOLS=0,3"]
    assert commands(start, "_FF_NOZZLE_CLEAN") == [
        "_FF_NOZZLE_CLEAN TOOLS=0,3 TEMP=220.0"]
    assert commands(start, "T0") == ["T0"]


def test_explicit_start_print_without_tools_uses_tool_not_published_status(
        macro_templates):
    printer = {"gcode_macro FF_BEFORE_PRINT_START":
               {"prepare": 0, "prepare_on_m23": 0},
               "ff_print": {"active": True, "tools": [0, 3]}}
