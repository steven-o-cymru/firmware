def test_header_beyond_bounded_head_is_not_read(ff_print, tmp_path):
    path = tmp_path / "late-header.gcode"
    path.write_bytes(b"; padding\n" * (ff_print.HEAD_BYTES // 10 + 1)
                     + b"; HEADER_BLOCK_START\n; filament: 1\n"
                       b"; HEADER_BLOCK_END\nT2\nT3\n")
    assert "tools" not in ff_print._parse_metadata(path)


def test_only_the_bounded_head_is_read(ff_print, tmp_path, monkeypatch):
    path = gcode_file(tmp_path, body="T1\nT3\n", header=False)
    real_open = open
    reads = []

    class Recording:
        def __init__(self, fh):
            self.fh = fh

        def __enter__(self):
            return self

        def __exit__(self, *_args):
            self.fh.close()
            return False

        def read(self, size):
            reads.append(size)
            return self.fh.read(size)

    monkeypatch.setattr(ff_print, "open",
                        lambda name, mode: Recording(real_open(name, mode)),
                        raising=False)
    ff_print._parse_metadata(path)
    assert reads == [ff_print.HEAD_BYTES]


