def test_m23_then_reset_cannot_supply_tools_to_manual_start(
        ff_print, tmp_path, macro_templates):
    path = gcode_file(tmp_path, "1,4", "T0\nT3\n", name="a.gcode")
    selected = {"path": None}
    job, _calls = make_job(ff_print, tmp_path, "M23",
                           on_file=lambda _gcmd: selected.update(path=path))
    job._cmd_start("M23", file_command(path))
    assert selected["path"] == path
    # Pinned virtual_sdcard's SDCARD_RESET_FILE does not notify ff_print;
    # print_stats stays standby because M24 never started the selected file.
    selected["path"] = None
    assert job.get_status(0)["active"]

    start = render(macro_templates["START_PRINT"], {"TOOL": "2"},
                   {"ff_print": job.get_status(0)})
    assert commands(start, "_FF_NOZZLE_CLEAN") == [
        "_FF_NOZZLE_CLEAN TOOLS=2 TEMP=220.0"]


def test_failed_file_selection_cannot_supply_tools_to_later_start(
        ff_print, tmp_path, macro_templates):
    path = gcode_file(tmp_path, "1,4", "T0\nT3\n", name="unselected.gcode")

    def fail(_gcmd):
        raise ValueError("virtual_sdcard rejected the file")

    job, calls = make_job(ff_print, tmp_path, on_file=fail)
    with pytest.raises(ValueError, match="rejected"):
        job._cmd_start("SDCARD_PRINT_FILE", file_command(path))
    assert calls == [("before", "FF_BEFORE_PRINT_START "
                      "ORIGIN=SDCARD_PRINT_FILE TOOL=0 TOOLS=0,3")]
    assert job.get_status(0)["tools"] == [0, 3]

    start = render(macro_templates["START_PRINT"], {"TOOL": "2"},
                   {"ff_print": job.get_status(0)})
    assert commands(start, "_FF_NOZZLE_CLEAN") == [
        "_FF_NOZZLE_CLEAN TOOLS=2 TEMP=220.0"]


def test_file_a_followed_by_successful_file_b_uses_only_b(
        ff_print, tmp_path):
    path_a = gcode_file(tmp_path, "1,4", "T0\nT3\n", name="a.gcode")
    path_b = gcode_file(tmp_path, "2,4", "T1\nT3\n", name="b.gcode")
    job, calls = make_job(ff_print, tmp_path)
    job._cmd_start("SDCARD_PRINT_FILE", file_command(path_a))
    job.active = False  # File A has finished before file B is selected.
    job._cmd_start("SDCARD_PRINT_FILE", file_command(path_b))

    assert [script for kind, script in calls if kind == "before"] == [
        "FF_BEFORE_PRINT_START ORIGIN=SDCARD_PRINT_FILE TOOL=0 TOOLS=0,3",
        "FF_BEFORE_PRINT_START ORIGIN=SDCARD_PRINT_FILE TOOL=1 TOOLS=1,3",
    ]
    assert job.get_status(0)["tools"] == [1, 3]


