def test_existing_nozzle_clean_purges_only_the_forwarded_tools(
        macro_templates):
    printer = {"gcode_macro _FF_FILAMENT": {
        "default_temp": 220, "tool_material": ["PLA"] * 4,
        "temps": {"PLA": 220}, "load_feed_thin": 100,
        "load_feed": 200, "purge_length": 50, "purge_fan": .6,
        "purge_retract": 5},
        "configfile": {"settings": {"extruder%d" % n: {
            "nozzle_diameter": .4} for n in range(4)}}}
    for n in range(4):
        printer["tool T%d" % n] = {"extruder": "extruder%d" % n}
    output = render(macro_templates["_FF_NOZZLE_CLEAN"],
                    {"TOOLS": "1,3", "TEMP": "220"}, printer)
    assert commands(output, "_FF_FILAMENT_PREP") == [
        "_FF_FILAMENT_PREP TOOL=1 TEMP=220 ALLOW_PRINTING=1",
        "_FF_FILAMENT_PREP TOOL=3 TEMP=220 ALLOW_PRINTING=1",
    ]
    assert len(commands(output, "G1 E50")) == 2
    assert commands(output, "_FF_NOZZLE_WIPE") == [
        "_FF_NOZZLE_WIPE TOOL=1 TEMP=220",
        "_FF_NOZZLE_WIPE TOOL=3 TEMP=220",
    ]
