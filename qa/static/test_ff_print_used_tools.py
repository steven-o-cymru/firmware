def gcode_file(tmp_path, field=None, body="T0\nG1 X1 E1\n", header=True,
               name="print.gcode"):
    prefix = ("; HEADER_BLOCK_START\n; generated by OrcaSlicer\n"
              "; filament: %s\n; HEADER_BLOCK_END\n" % field
              if header else "")
    path = tmp_path / name
    path.write_text(prefix + body)
    return path


@pytest.mark.parametrize("field,body,participants,initial", [
    ("1", "T0\nG1 E1\n", [0], 0),
    ("3", "T2\nG1 E1\n", [2], 2),
    ("1,2", "T0\nT1\n", [0, 1], 0),
    ("2,4", "T1\nT3\n", [1, 3], 1),
    ("1,2,3,4", "T0\nT1\nT2\nT3\n", [0, 1, 2, 3], 0),
    # Orca Type 2 tower headers can list participants in priming order.
    ("4,1", "T0\nT3\n", [0, 3], 0),
    ("4,1,4,1", "T0\nT3\n", [0, 3], 0),
])
def test_orca_participants_are_independent_of_initial_tool(
        ff_print, tmp_path, field, body, participants, initial):
    metadata = ff_print._parse_metadata(gcode_file(tmp_path, field, body))
    assert metadata["tools"] == participants
    assert metadata["tool"] == initial


@pytest.mark.parametrize("field", ["1,5", "1,x", "1,", "0,2", "", "1,,2"])
def test_invalid_header_derives_no_tools(ff_print, tmp_path, field):
    body = "T3 ; actual selection\nG1 E1\nT1\n"
    metadata = ff_print._parse_metadata(gcode_file(tmp_path, field, body))
    # A partial list is worse than none, and the body is not scanned instead.
    assert "tools" not in metadata
    assert metadata["tool"] == 3  # Existing first-bare-Tn rule.


